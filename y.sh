gg() { git grep -I "$@" 2>/dev/null | tr -d '\r'; }
n() { wc -l | tr -d ' '; }
section() { printf '\n## %s\n' "$1"; }

# occ [-i] LABEL REGEX PATHSPEC... -> number of matches and of files
occ() {
  local ci=""; [ "$1" = "-i" ] && { ci="-i"; shift; }
  local label=$1 re=$2; shift 2
  printf '  %-48s %6s hits in %5s files\n' "$label" \
    "$(gg $ci -h -o -E -e "$re" -- "$@" | n)" \
    "$(gg $ci -l -E -e "$re" -- "$@" | n)"
}

# tally [-i] LABEL TOP REGEX PATHSPEC... -> distinct matches with counts
tally() {
  local ci=""; [ "$1" = "-i" ] && { ci="-i"; shift; }
  local label=$1 top=$2 re=$3; shift 3
  local out; out=$(gg $ci -h -o -E -e "$re" -- "$@" | sed -E 's/[[:space:]]+/ /g' | sort | uniq -c | sort -rn | head -n "$top")
  echo "  $label:"
  if [ -n "$out" ]; then echo "$out" | sed 's/^/    /'; else echo "    (none)"; fi
}

# files LABEL MAX PATHSPEC... -> tracked files matching, with total
files() {
  local label=$1 max=$2; shift 2
  local all; all=$(git ls-files -- "$@")
  echo "  $label (total $(printf '%s' "$all" | grep -c .)):"
  [ -n "$all" ] && echo "$all" | head -n "$max" | sed 's/^/    /'
}

