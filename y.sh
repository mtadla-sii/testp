redact() {
  perl -pe '
    BEGIN {
      my @w = map { quotemeta } grep { length } split /\|/, ($ENV{REDACT_WORDS} // "");
      $re = @w ? join("|", @w) : undef;
    }
    s#\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b#<email>#g;
    s#\b(https?|wss?)://[^/\s"\x27\x60)<>]+#$1://<host>#gi;
    s#\bdev\.azure\.com/[^/\s"\x27]+#dev.azure.com/<org>#gi;
    s#\b[A-Za-z0-9-]+\.(azurewebsites\.net|azurecr\.io|blob\.core\.windows\.net|vault\.azure\.net|database\.windows\.net|servicebus\.windows\.net|azure-api\.net|azurefd\.net|onmicrosoft\.com|visualstudio\.com|ghe\.com)\b#<host>.$1#gi;
    s#\b[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\b#<guid>#g;
    s#\b(?:\d{1,3}\.){3}\d{1,3}\b#<ip>#g;
    s/$re/<X>/gi if defined $re;
  '
}

main 2>&1 | redact
